#!/usr/bin/env python3
"""Freeze the Classic Daily schedule so changing the answer pool doesn't move past puzzles.

The game picks day N's answer like this (keep in step with src/game.js):

  1. days 1..len(SCHEDULE) are fixed: data/schedule.js lists each day's Coasterpedia page;
  2. later days go through the answer pool shuffled with SHUFFLE_SEED, coasters that haven't
     been a Daily answer yet first, then the rest, and repeat.

With an empty schedule that is exactly the old plain shuffle. Changing the pool only reorders
days after the frozen ones, so freeze up to a couple of days ahead *before* writing a new pool.
import_coasterpedia.py does that automatically; run this by hand only to freeze further ahead:

    python3 scripts/schedule.py            # freeze through today + AHEAD days
    python3 scripts/schedule.py --show 5   # print the next 5 days' answers
"""

import argparse
import datetime as dt
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
COASTERS_PATH = ROOT / "data" / "coasters.js"
SCHEDULE_PATH = ROOT / "data" / "schedule.js"

EPOCH = dt.date(2026, 1, 1)  # puzzle No. 1 (EPOCH in game.js)
SHUFFLE_SEED = 0x7400513     # SHUFFLE_SEED in game.js
AHEAD = 2                    # local midnight arrives up to a day earlier elsewhere; keep a margin
M32 = 0xFFFFFFFF


def imul(a, b):
    return (a * b) & M32


def mulberry32(a):
    """Same generator as game.js, on unsigned 32-bit ints (identical bits, so identical output)."""
    a &= M32

    def rand():
        nonlocal a
        a = (a + 0x6D2B79F5) & M32
        t = imul(a ^ (a >> 15), 1 | a)
        t = ((t + imul(t ^ (t >> 7), 61 | t)) & M32) ^ t
        return ((t ^ (t >> 14)) & M32) / 4294967296

    return rand


def shuffled(items, seed):
    rand = mulberry32(seed)
    out = list(items)
    for i in range(len(out) - 1, 0, -1):
        j = int(rand() * (i + 1))
        out[i], out[j] = out[j], out[i]
    return out


def read_js_array(path, var):
    if not path.exists():
        return []
    text = path.read_text(encoding="utf-8")
    m = re.search(rf"window\.{var}\s*=\s*(\[.*\])\s*;", text, re.S)
    return json.loads(m.group(1)) if m else []


def pool_pages(coasters):
    """Answer pool in data-file order, as Coasterpedia page titles (game.js POOL)."""
    pool = [c for c in coasters if c.get("answer")] or coasters
    return [c["page"] for c in pool]


def order_after(frozen, pool):
    """Answer order for the days after the frozen ones (game.js ORDER)."""
    used = set(frozen)
    return shuffled([p for p in pool if p not in used], SHUFFLE_SEED) + shuffled(
        [p for p in pool if p in used], SHUFFLE_SEED
    )


def answer_for(day, frozen, pool):
    if day <= len(frozen):
        return frozen[day - 1]
    order = order_after(frozen, pool)
    return order[(day - len(frozen) - 1) % len(order)]


def day_number(date):
    return (date - EPOCH).days + 1


def write_schedule(days):
    body = ",\n".join("  " + json.dumps(p, ensure_ascii=False) for p in days)
    SCHEDULE_PATH.write_text(
        "// Generated by scripts/schedule.py: the Classic Daily answer for days 1..N, by Coasterpedia page.\n"
        "// Frozen so that changes to the answer pool never move a puzzle that's already been played.\n"
        f"window.SCHEDULE = [\n{body}\n];\n",
        encoding="utf-8",
    )


def freeze(coasters=None, through=None):
    """Freeze every day up to `through` (default today + AHEAD) using the current pool.

    Call this with the pool that is live *now*, before replacing it. Returns days added.
    """
    coasters = read_js_array(COASTERS_PATH, "COASTERS") if coasters is None else coasters
    pool = pool_pages(coasters)
    if not pool:
        return 0
    frozen = read_js_array(SCHEDULE_PATH, "SCHEDULE")
    last = day_number(through or dt.date.today() + dt.timedelta(days=AHEAD))
    if last <= len(frozen):
        return 0
    order = order_after(frozen, pool)
    added = [order[(d - len(frozen) - 1) % len(order)] for d in range(len(frozen) + 1, last + 1)]
    write_schedule(frozen + added)
    return len(added)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--through", type=dt.date.fromisoformat, help="freeze through this date (YYYY-MM-DD)")
    ap.add_argument("--show", type=int, metavar="N", help="print today's and the next N-1 days' answers")
    args = ap.parse_args()
    if args.show:
        coasters = read_js_array(COASTERS_PATH, "COASTERS")
        frozen, pool = read_js_array(SCHEDULE_PATH, "SCHEDULE"), pool_pages(coasters)
        today = dt.date.today()
        for i in range(args.show):
            day = day_number(today) + i
            tag = "frozen" if day <= len(frozen) else ""
            print(f"No. {day:3}  {today + dt.timedelta(days=i)}  {answer_for(day, frozen, pool)}  {tag}")
        return
    n = freeze(through=args.through)
    total = len(read_js_array(SCHEDULE_PATH, "SCHEDULE"))
    print(f"Froze {n} more days; {SCHEDULE_PATH.relative_to(ROOT)} now fixes days 1-{total}.")


if __name__ == "__main__":
    main()
